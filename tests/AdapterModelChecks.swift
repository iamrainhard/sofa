import Foundation

@main struct AdapterModelChecks {
    @MainActor static func main() {
        let android = RemoteModel(previewState: "android-home")
        precondition(android.ready && android.canStepVolume && android.canSetVolume)
        android.receive(["event": "status", "value": "offline", "session": "old-tv-session"])
        precondition(android.ready, "Stale adapter callbacks cannot change the current connection")
        precondition(android.platformTitle == "Google / Android TV")
        precondition(!android.activePlatform.hasInstalledAppCatalog)
        android.receive(["event": "state", "value": ["statetype": "android_state", "power": false, "appname": "Netflix"]])
        precondition(android.powerState == .standby && android.activeDestination == nil)
        android.receive(["event": "state", "value": ["statetype": "android_state", "power": true, "appname": "YouTube"]])
        precondition(android.powerState == .on && android.activeDestination?.name == "YouTube")
        precondition(TVPowerState.reported(by: ["statetype": "android_state", "appname": "Netflix"]) == .unknown)
        android.receive(["event": "volume_control_unavailable"])
        precondition(!android.canSetVolume && android.canStepVolume)
        android.receive(["event": "status", "value": "offline"])
        precondition(!android.hasVolume && !android.canStepVolume && android.powerState == .unknown)
        precondition(android.activeDestination == nil)
        android.receive(["event": "status", "value": "pairing"])
        precondition(android.settingsVisible && android.pendingPair && !android.isBusy)
        android.pin = "AB12CD"
        precondition(android.validPIN)
        let vidaa = RemoteModel(previewState: "remote")
        precondition(vidaa.ready && vidaa.canSetVolume && vidaa.canStepVolume)
        vidaa.pin = "1234"
        precondition(vidaa.validPIN)
        vidaa.receive(["event": "state", "value": ["statetype": "remote_launcher"]])
        precondition(vidaa.powerState == .on && vidaa.sourceName == "VIDAA Home")
        vidaa.receive(["event": "state", "value": ["statetype": "fake_sleep_0"]])
        precondition(vidaa.powerState == .standby)
        vidaa.receive(["event": "state", "value": ["statetype": "app", "appname": "Netflix"]])
        precondition(vidaa.canConfigureSeeking && vidaa.seekingMode == .automatic)
        vidaa.setSeekingMode(.directionalKeys)
        precondition(vidaa.seekingMode == .directionalKeys)
        vidaa.receive(["event": "state", "value": ["statetype": "app", "appname": "YouTube"]])
        precondition(vidaa.seekingMode == .automatic, "One app's override cannot change another app")
        vidaa.receive(["event": "state", "value": ["statetype": "app", "appname": "Netflix"]])
        precondition(vidaa.seekingMode == .directionalKeys, "Remember the app's mode when returning")
        vidaa.setSeekingMode(.automatic)
        precondition(vidaa.seekingMode == .automatic)
        vidaa.disconnect()
        precondition(!vidaa.hasVolume && !vidaa.canSetVolume && vidaa.apps.isEmpty)
        let samsung = RemoteModel(previewState: "samsung-remote")
        precondition(samsung.ready && samsung.canSetVolume && samsung.canStepVolume)
        precondition(samsung.activePlatform.usesTVApproval && !samsung.validPIN)
        precondition(!samsung.hasInstalledAppCatalog)
        samsung.receive(["event": "volume_control_unavailable"])
        precondition(!samsung.canSetVolume && samsung.canStepVolume && !samsung.muteStateKnown)
        precondition(samsung.muteActionTitle == "Toggle mute")
        samsung.receive(["event": "capabilities", "absolute_volume": true])
        precondition(!samsung.canSetVolume, "Capability alone cannot enable a slider without a reading")
        samsung.receive(["event": "volume", "value": 42, "muted": true, "source": "readback"])
        precondition(samsung.canSetVolume && samsung.muteStateKnown && samsung.muteActionTitle == "Unmute")
        samsung.receive(["event": "volume", "value": 42, "mute_known": false, "source": "readback"])
        precondition(samsung.canSetVolume && !samsung.muteStateKnown && samsung.muteActionTitle == "Toggle mute")
        samsung.receive(["event": "capabilities", "installed_apps": true])
        precondition(samsung.hasInstalledAppCatalog)
        samsung.receive(["event": "state", "value": ["statetype": "samsung_state", "power": true]])
        precondition(samsung.powerState == .on && samsung.activeDestination == nil)
        samsung.receive(["event": "status", "value": "pairing"])
        samsung.receive(["event": "approval", "waiting": true])
        precondition(samsung.waitingForTVApproval && !samsung.canStepVolume && !samsung.canSetVolume)
        samsung.receive(["event": "approval", "waiting": false])
        precondition(!samsung.waitingForTVApproval && !samsung.validPIN)
        samsung.receive(["event": "status", "value": "ready"])
        precondition(samsung.canStepVolume && !samsung.canSetVolume && !samsung.hasInstalledAppCatalog)
        precondition(samsung.powerState == .unknown)
        precondition(TVConnectionPlatform.vidaa.keychainService == "com.rain.luma-remote.vidaa")
        precondition(TVConnectionPlatform.androidtv.keychainService == "com.rain.sofa.androidtv")
        precondition(Set([TVConnectionPlatform.vidaa, .androidtv, .samsung].map { $0.keychainService }).count == 3)
        precondition(Set([TVConnectionPlatform.vidaa, .androidtv, .samsung].map { $0.certificateKey(host: "192.168.1.4") }).count == 3)
        print("Adapter UI state checks passed (VIDAA, Android and experimental Samsung)")
    }
}
